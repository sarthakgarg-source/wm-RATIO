"""Paste evidence/<run>/analysis.log into section 4 of T03.md (between '## 4. Results' and '## 5. Findings'). Sections 1–3
are never touched (check_prereg.py proves it). Also sets the header's Status and Run date.
    python tests/T03/fill_writeup.py [run-name]"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__)); RUN = sys.argv[1] if len(sys.argv) > 1 else "headline"
EV = os.path.join(HERE, "evidence", RUN); MD = os.path.join(HERE, "T03.md")


def main():
    txt = open(MD, encoding="utf-8").read(); log = open(os.path.join(EV, "analysis.log"), encoding="utf-8").read()
    import json
    T = json.load(open(os.path.join(EV, "tables.json")))
    a = txt.index("## 4. Results"); b = txt.index("## 5. Findings")
    head = txt[a:txt.index("\n", a) + 1]
    body = f"\n_Generated by `tests/T03/analyse.py` from `evidence/{RUN}/` on {T['run_date']}; {T['draws']:,} draws per null. Nothing below is typed._\n\n" + log.strip() + "\n\n"
    txt = txt[:a] + head + body + txt[b:]
    txt = re.sub(r"^\*\*Run date:\*\*.*$", f"**Run date:** {T['run_date']} (run `{RUN}`)", txt, flags=re.M)
    txt = re.sub(r"^\*\*Status:\*\* (DRAFT|RUNNING)", "**Status:** COMPLETE", txt, flags=re.M)
    open(MD, "w", encoding="utf-8").write(txt); print("section 4 filled from", EV)


if __name__ == "__main__":
    main()
